/**
 * * Aritomético em sequência
 * () Potenciação
 * **
 * * / % Multiplicação / Divição / Resto da divição
 * + Adição / Concatenação
 * - Subtração
 */
 const num1 = 5;
 const num2 = 2;
 const num3 = 10;
 console.log((num1 + num2) * num3);

 /*
 Incremento = ++
 Decremento = --
 */
 let contador = 1;
 console.log(contador++);
 console.log(contador);

 const passo = 2;
 let cont = 0;
 cont *= passo;
 console.log(cont);

 